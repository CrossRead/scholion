# ── helpers ────────────────────────────────────────────────────────────────
def months(start: str, end: str) -> list[str]:
    y0, m0 = (int(x) for x in start.split("-"))
    y1, m1 = (int(x) for x in end.split("-"))
    out = []
    while (y0, m0) <= (y1, m1):
        out.append(f"{y0:04d}-{m0:02d}")
        m0 += 1
        if m0 == 13:
            m0, y0 = 1, y0 + 1
    return out


def ramp(vals: list[str], lo: float, hi: float, rnd: random.Random, noise: float, nd: int = 1) -> dict:
    """A smooth transition lo→hi over a list of months with reproducible noise."""
    n = max(len(vals) - 1, 1)
    return {m: round(lo + (hi - lo) * i / n + rnd.uniform(-noise, noise), nd)
            for i, m in enumerate(vals)}


def series(points: list[tuple[str, float]]) -> list[dict]:
    return [{"date": d, "value": v} for d, v in points]



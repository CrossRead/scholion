def occupied_by_real_profile(out: Path) -> bool:
    """Whether the directory holds data that is NOT demonstration data.

    The main danger of this script is overwriting somebody's real profile. The sign of a
    demo is the synthetic field in _meta. A file without it counts as real, because an
    error in that direction is irreversible, while in the other one it costs a --force flag.
    """
    for p in out.glob("*.json"):
        try:
            d = json.loads(p.read_text(encoding="utf-8"))
        except Exception:
            return True
        m = d.get("_meta") or d.get("meta") or {}
        if not (isinstance(m, dict) and m.get("synthetic")):
            return True
    return False


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        prog="scholion demo",
        description="Build a synthetic demo profile (the data are invented).")
    ap.add_argument("--out", default=None,
                    help="profile directory (demo/profile by default)")
    ap.add_argument("--force", action="store_true",
                    help="overwrite the directory even if it holds unmarked data")
    ap.add_argument("--quiet", action="store_true")
    a = ap.parse_args(argv)

    out = Path(a.out).expanduser().resolve() if a.out else _default_out()
    if out.exists() and occupied_by_real_profile(out) and not a.force:
        print(f"✗ {out} holds data with no synthetic mark — it looks like a real profile.\n"
              f"  The demo is not written there. If you are sure it is not, repeat with --force.", file=sys.stderr)
        return 1

    out.mkdir(parents=True, exist_ok=True)
    files = build_all()
    for name, data in files.items():
        (out / name).write_text(
            json.dumps(data, ensure_ascii=False, indent=2, sort_keys=False) + "\n",
            encoding="utf-8")
    (out / "index.md").write_text(INDEX_MD, encoding="utf-8")

    if not a.quiet:
        total = sum((out / n).stat().st_size for n in files) + (out / "index.md").stat().st_size
        print(f"✓ demo profile built: {out}")
        print(f"  {len(files) + 1} files, {total // 1024} KB, generation is deterministic (seed {SEED})")
        print()
        print("  To look at it:")
        # An absolute path is printed: a relative one holds only while the person has not
        # changed directory, and the command from the hint gets copied anywhere.
        rel = out
        print(f"    SCHOLION_PROFILE_DIR={rel} scholion overview")
        print(f"    SCHOLION_PROFILE_DIR={rel} scholion serve")
    return 0


if __name__ == "__main__":
    sys.exit(main())

#!/usr/bin/env python3
"""demo.py — a synthetic demo profile in one command (`scholion demo`).

Why. A person opening the project for the first time should not have to start by
loading their own genome. What they need is a working dashboard after one command —
otherwise the funnel breaks off at the first step.

**The rule of the demo: this is a different person.** Not the owner of the project
with altered numbers, but a self-contained fictional case — a different sex, a
different age, a different clinical axis. A picture that coincides with anybody's
real profile counts as a defect: a set of findings is personal data in itself, even
when every figure has been replaced. What has to be checked is not «do the numbers
differ» but «is the story recognisable».

The demo persona: a woman of 33, vegetarian, amateur running. The main line is iron
deficiency without anaemia, B12 deficiency and subclinical hypothyroidism against
autoimmune thyroiditis; separately factor V Leiden against a combined oral
contraceptive. Lipids, carbohydrate metabolism and male endocrinology are
deliberately clean in the demo.

The numbers are chosen so that ALL layers of the engine work, the honesty layer
included: some findings are deliberately doubtful, some panels deliberately
incomplete, some percentiles deliberately marked unreliable. A demo in which
everything is green does not show the product.

    python3 src/tools/make_demo_profile.py
    SCHOLION_PROFILE_DIR=demo/profile python3 -m scholion overview

Generation is deterministic: the same input yields a byte-identical profile, so the
files serve both as a test fixture and as a source of screenshots.
"""
